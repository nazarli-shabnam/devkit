import * as path from 'path';
import * as os from 'os';
import * as fs from 'fs-extra';
import prompts from 'prompts';
import * as init from '../../src/commands/init';
import { runGenerate } from '../../src/commands/generate';
import { runShareExport, runShareImport } from '../../src/commands/share';
import { listSnapshots } from '../../src/core/snapshot/storage';
import { GENERATED_MARKER } from '../../src/utils/overwrite';
import { logger } from '../../src/utils/logger';

describe('overwrite protection', () => {
  let root: string;
  const originalCwd = process.cwd();
  const read = (name: string): Promise<string> => fs.readFile(path.join(root, name), 'utf-8');
  const interactive = (value: boolean): void => {
    jest.spyOn(init, 'isInteractive').mockReturnValue(value);
  };

  beforeEach(async () => {
    jest.spyOn(logger, 'warn').mockImplementation();
    jest.spyOn(logger, 'info').mockImplementation();
    jest.spyOn(logger, 'success').mockImplementation();
    jest.spyOn(logger, 'debug').mockImplementation();
    root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'devkit-overwrite-')));
    await fs.writeFile(path.join(root, '.dev-env.yml'), 'name: original\ndatabases:\n  - type: redis\n');
    process.chdir(root);
    interactive(false);
  });

  afterEach(async () => {
    process.chdir(originalCwd);
    await fs.remove(root).catch(() => {});
    jest.restoreAllMocks();
  });

  describe('generate', () => {
    it('refuses to replace a hand-written compose file without --force (non-interactive)', async () => {
      await fs.writeFile(path.join(root, 'docker-compose.yml'), '# hand edited\nservices: {}\n');
      await expect(runGenerate({})).rejects.toThrow(/already exists and was not generated by envkit.*--force/);
      expect(await read('docker-compose.yml')).toContain('# hand edited');
    });

    it('overwrites it with --force', async () => {
      await fs.writeFile(path.join(root, 'docker-compose.yml'), '# hand edited\n');
      await runGenerate({ force: true });
      expect(await read('docker-compose.yml')).toContain('redis');
    });

    it('stamps the output and regenerates its own earlier output without asking', async () => {
      await runGenerate({});
      expect(await read('docker-compose.yml')).toContain(GENERATED_MARKER);
      await fs.writeFile(path.join(root, '.dev-env.yml'), 'name: original\ndatabases:\n  - type: mysql\n');
      await runGenerate({});
      expect(await read('docker-compose.yml')).toContain('mysql');
    });

    it('asks in a terminal and respects a "no"', async () => {
      interactive(true);
      await fs.writeFile(path.join(root, 'docker-compose.yml'), '# mine\n');
      prompts.inject([false]);
      await runGenerate({});
      expect(await read('docker-compose.yml')).toBe('# mine\n');
      prompts.inject([true]);
      await runGenerate({});
      expect(await read('docker-compose.yml')).toContain(GENERATED_MARKER);
    });

    it('does not touch the file for --dry-run', async () => {
      await fs.writeFile(path.join(root, 'docker-compose.yml'), '# mine\n');
      jest.spyOn(process.stdout, 'write').mockImplementation(() => true);
      await expect(runGenerate({ dryRun: true })).resolves.toBeUndefined();
      expect(await read('docker-compose.yml')).toBe('# mine\n');
    });
  });

  describe('share export', () => {
    it('protects foreign files but re-exports over its own output', async () => {
      await fs.writeFile(path.join(root, 'dev-env.shared.yml'), 'name: precious\n');
      await expect(runShareExport({})).rejects.toThrow(/--force/);
      expect(await read('dev-env.shared.yml')).toBe('name: precious\n');

      await runShareExport({ force: true });
      expect(await read('dev-env.shared.yml')).toContain(GENERATED_MARKER);
      await expect(runShareExport({})).resolves.toBeUndefined();
    });
  });

  describe('share import', () => {
    beforeEach(async () => {
      await fs.writeFile(path.join(root, 'incoming.yml'), 'name: imported\n');
    });

    it('does not replace the project config without --force when non-interactive', async () => {
      await expect(runShareImport('incoming.yml', {})).rejects.toThrow(/\.dev-env\.yml already exists.*--force/);
      expect(await read('.dev-env.yml')).toContain('name: original');
    });

    it('with --force replaces it and saves the previous config as a snapshot', async () => {
      await runShareImport('incoming.yml', { force: true });
      expect(await read('.dev-env.yml')).toContain('name: imported');

      const snapshots = await listSnapshots(root);
      expect(snapshots).toHaveLength(1);
      expect(snapshots[0].name).toMatch(/^pre-import-/);
      const saved = await fs.readFile(
        path.join(root, '.devkit', 'snapshots', snapshots[0].name, 'dev-env.yml'),
        'utf-8'
      );
      expect(saved).toContain('name: original');
    });

    it('a declined prompt leaves the config and creates no snapshot', async () => {
      interactive(true);
      prompts.inject([false]);
      await runShareImport('incoming.yml', {});
      expect(await read('.dev-env.yml')).toContain('name: original');
      expect(await listSnapshots(root)).toHaveLength(0);
    });

    it('importing to a new file needs no confirmation and makes no backup', async () => {
      await runShareImport('incoming.yml', { output: 'fresh.yml' });
      expect(await read('fresh.yml')).toContain('name: imported');
      expect(await listSnapshots(root)).toHaveLength(0);
    });
  });
});
