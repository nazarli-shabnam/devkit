import prompts from 'prompts';
import { isInteractive } from '../commands/init';
import { fileExists, readFile } from './file-ops';

/** Text envkit puts in the first lines of files it generates, so it can recognise them later. */
export const GENERATED_MARKER = 'Generated by envkit';

export function generatedHeader(what: string): string {
  return `# ${GENERATED_MARKER} (${what}). Re-run the command to regenerate; manual edits will be overwritten.\n`;
}

export interface OverwriteOptions {
  /** Overwrite without asking. */
  force?: boolean;
  /** How the file is called in messages. */
  displayName: string;
  /** The file is regenerated output: overwrite silently if it carries the envkit header. */
  regenerable?: boolean;
}

async function isEnvkitGenerated(target: string): Promise<boolean> {
  const head = (await readFile(target)).slice(0, 400);
  return head.includes(GENERATED_MARKER);
}

/**
 * May `target` be written? Missing files, `--force`, and files envkit itself generated earlier
 * (when `regenerable`) always may. Anything else is somebody's work: ask in a terminal, and fail
 * with a hint when there is nobody to ask (CI, pipes).
 */
export async function confirmOverwrite(target: string, options: OverwriteOptions): Promise<boolean> {
  if (!(await fileExists(target)) || options.force) return true;
  if (options.regenerable && (await isEnvkitGenerated(target))) return true;

  if (!isInteractive()) {
    throw new Error(
      `${options.displayName} already exists${options.regenerable ? ' and was not generated by envkit' : ''}. ` +
        'Re-run with --force to overwrite it.'
    );
  }

  const answer = await prompts(
    { type: 'confirm', name: 'value', message: `${options.displayName} already exists. Overwrite it?`, initial: false },
    { onCancel: () => false }
  );
  return answer.value === true;
}
